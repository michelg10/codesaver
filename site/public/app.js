  function spinnerLines(maxW) {
    const { head, paren } = spinnerRuns(sp, now);
    const SP = { t: ' ', c: [1, 1, 1], a: 0 };
    const one = paren.length ? [...head, SP, ...paren] : head;
    if (runsWidth(ctx, one, ui) <= maxW) return [one];
    const lines = [head], items = [];
    for (const r of paren) {
      const lastItem = items[items.length - 1];
      if (r.t === ' · ' && lastItem) lastItem.push({ ...r, t: ' ·' });
      else if (r.t === ')' && lastItem) lastItem.push(r);
      else if (lastItem && lastItem.length === 1 && lastItem[0].t === '(') lastItem.push(r);
      else items.push([r]);
    }
    let cur = [];
    for (const it of items) {
      const cand = cur.length ? [...cur, SP, ...it] : it;
      if (cur.length && runsWidth(ctx, cand, ui) > maxW) { lines.push(cur); cur = it; } else cur = cand;
    }
    if (cur.length) lines.push(cur);
    return lines;
  }

