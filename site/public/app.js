// ── small helpers ─────────────────────────────────────────────────────────
const clamp = (x, a, b) => Math.min(b, Math.max(a, x));
const rand = (a, b) => a + (b - a) * Math.random();
const smooth01 = x => { const t = clamp(x, 0, 1); return t * t * (3 - 2 * t); };
const expTail = (base, mean, cap) => Math.min(cap, base - Math.log(Math.max(1e-9, Math.random())) * mean);
const gauss = (m, s) => { let u = 0; while (!u) u = Math.random(); return m + s * Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * Math.random()); };
const timeString = s => { s = Math.max(0, Math.floor(s)); return s < 60 ? s + 's' : Math.floor(s / 60) + 'm ' + (s % 60) + 's'; };
const countString = v => v < 1000 ? String(Math.floor(v)) : (v / 1000).toFixed(1) + 'k';
const mix = (a, b, t) => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t];
const rgba = (c, a = 1) => `rgba(${Math.round(c[0] * 255)},${Math.round(c[1] * 255)},${Math.round(c[2] * 255)},${a})`;

