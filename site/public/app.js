const TEMPO = 2.2, TICK_HZ = 60;
function cellNoise(c, r, salt) {   // stable per-cell hash in [0,1)
  let h = Math.imul(c | 0, 0x9E3779B1) ^ Math.imul(r | 0, 0x85EBCA77) ^ salt;
  h = Math.imul(h ^ (h >>> 16), 0x7FEB352D); h = Math.imul(h ^ (h >>> 15), 0x846CA68B); h ^= h >>> 16;
  return (h >>> 0) / 4294967296;
}
function burnState(c, r, age) {
  const h = cellNoise(c, r, 0x5EED);
  if (h >= 0.05) return 0;
  const fr = x => x - Math.floor(x);
  const dur = 5 + fr(h * 83.13) * 9;
  if (age >= dur) return 0;
  const slice = Math.floor((age + Math.floor(fr(h * 517) * 8)) / 4);
  return ((fr(h * 259.3) < 0.5) !== ((slice & 1) === 1)) ? 1 : 2;
}
function blipLevel(age, n1, n2) {
  if (n1 >= 0.22 || age < 0) return 0;
  const t1 = age - Math.floor(n2 * 6);
  if (t1 < 0) return 0;
  if (t1 <= 1) return 1.35;
  if (t1 <= 4) return 0.95;
  const resurge = n1 > 0.13;
  if (resurge && t1 >= 6 && t1 <= 8) return 0.75;
  const g = t1 - (resurge ? 9 : 5);
  if (g < 0) return 0;
  const ghost = 0.30 * Math.exp(-g / 10);
  return ghost < 0.02 ? 0 : ghost;
}
const settledFade = age => { const t = Math.max(0, 1 - Math.max(0, age) / 5); return t * t; };

class Boom {
  constructor(g, ox, oy, colors, lines) {
    Object.assign(this, g);  // cols, rows, charW, lineH, L, T, W, H
    this.ox = ox; this.oy = oy;
    this.R = Math.max(Math.hypot(ox, oy), Math.hypot(this.W - ox, oy), Math.hypot(ox, this.H - oy), Math.hypot(this.W - ox, this.H - oy));
    this.wave1 = 0.85 * TEMPO; this.gap = 0.2 * TEMPO; this.wave2 = 0.85 * TEMPO;
    this.duration = this.gap + this.wave2 + 0.5;
    const n = this.cols * this.rows;
    this.state = new Uint8Array(n); this.ascii = new Uint8Array(n); this.hit = new Int32Array(n).fill(-1);
    this.h1 = new Float32Array(n); this.h2 = new Float32Array(n); this.color = colors;
    for (let r = 0; r < this.rows; r++) for (let c = 0; c < this.cols; c++) {
      const i = r * this.cols + c;
      const x = this.L + (c + 0.5) * this.charW, y = this.T + (r + 0.5) * this.lineH;
      const u = 1 - Math.pow(1 - Math.min(Math.hypot(x - ox, y - oy) / this.R, 0.999), 0.6);
      this.h1[i] = this.wave1 * u + (cellNoise(c, r, 0xB1) - 0.5) * 0.10;
      this.h2[i] = this.gap + this.wave2 * u + (cellNoise(c, r, 0xB2) - 0.5) * 0.12;
    }
    this.lines = lines.filter(l => l.trim().length > 2);
    this.pool = this.lines.join('').replace(/[^\x21-\x7e]/g, '');
    if (!this.pool) this.pool = '{}[]()<>=+-*/;:._';
    this.parts = []; this.trails = []; this.tick = 0;
    this.maxParts = Math.min(900, Math.round(n * 0.08));
  }
  secondHit(x, y) {
    return this.gap + this.wave2 * (1 - Math.pow(1 - Math.min(Math.hypot(x - this.ox, y - this.oy) / this.R, 0.999), 0.6));
  }
  advanceTo(t) { let k = 0; while (this.tick / TICK_HZ < t && k++ < 30) { this.tick++; this.step(); } }
  step() {
    const t = this.tick / TICK_HZ, dt = 1 / TICK_HZ, n = this.cols * this.rows;
    for (let i = 0; i < n; i++) {
      const s = this.state[i];
      if (s === 0 && t >= this.h1[i]) { this.state[i] = 1; this.hit[i] = this.tick; this.spawnDebris(i); this.spawnSpot(i); }
      else if (s === 1 && t >= this.h2[i]) { this.state[i] = 2; this.hit[i] = this.tick; }
    }
    const drag = Math.exp(-dt * 1.6 / TEMPO);
    for (const p of this.parts) {
      if (p.settled) continue;
      const ox = p.x, oy = p.y;
      p.vx *= drag; p.vy *= drag; p.x += p.vx * dt; p.y += p.vy * dt;
      if (p.x < 0 || p.y < 0 || p.x >= this.W || p.y >= this.H) { p.settled = true; p.gone = true; continue; }
      const sp = Math.hypot(p.vx, p.vy);
      if (sp > 250 / TEMPO) this.trail(ox, oy, p.x, p.y);
      if (p.decay < 0 && sp < 260 / TEMPO) p.decay = this.tick;
      if (sp < 42 / TEMPO) {
        p.settled = true;
        const c = Math.floor((p.x - this.L) / this.charW), r = Math.floor((p.y - this.T) / this.lineH);
        if (c >= 0 && r >= 0 && c < this.cols && r < this.rows) {
          const i = r * this.cols + c;
          this.state[i] = 3; this.ascii[i] = p.ch; this.hit[i] = p.decay >= 0 ? p.decay : this.tick;
        }
      }
    }
    const cut = this.tick - 16;
    if (this.trails.length && this.trails[0].tick < cut) this.trails = this.trails.filter(d => d.tick >= cut);
  }
  trail(x0, y0, x1, y1) {
    let a = Math.floor((x0 - this.L) / this.charW), b = Math.floor((y0 - this.T) / this.lineH);
    const c1 = Math.floor((x1 - this.L) / this.charW), r1 = Math.floor((y1 - this.T) / this.lineH);
    if (a === c1 && b === r1) return;
    const dx = Math.abs(c1 - a), dy = -Math.abs(r1 - b), sx = a < c1 ? 1 : -1, sy = b < r1 ? 1 : -1;
    let err = dx + dy;
    for (let k = 0; k < 64; k++) {
      if (a >= 0 && b >= 0 && a < this.cols && b < this.rows) this.trails.push({ i: b * this.cols + a, tick: this.tick });
      if (a === c1 && b === r1) break;
      const e2 = 2 * err;
      if (e2 >= dy) { err += dy; a += sx; }
      if (e2 <= dx) { err += dx; b += sy; }
    }
  }
  spawnSpot(i) {
    if (Math.random() >= 0.0015 || !this.lines.length) return;
    const c0 = i % this.cols, r0 = Math.floor(i / this.cols);
    const count = 2 + Math.floor(Math.random() * 4.999), start = Math.floor(Math.random() * this.lines.length);
    for (let li = 0; li < count; li++) {
      const r = r0 + li; if (r >= this.rows) break;
      const line = this.lines[(start + li) % this.lines.length];
      for (let k = 0; k < line.length && k < 44 && c0 + k < this.cols; k++) {
        const code = line.charCodeAt(k);
        if (code < 33 || code > 126) continue;
        const j = r * this.cols + c0 + k;
        if (this.state[j] > 1) continue;
        this.ascii[j] = code;
        if (this.state[j] === 1) this.hit[j] = this.tick;
      }
    }
  }
  spawnDebris(i) {
    if (this.parts.length >= this.maxParts || Math.random() >= 0.065) return;
    const c = i % this.cols, r = Math.floor(i / this.cols);
    const gx = this.L + (c + 0.5) * this.charW, gy = this.T + (r + 0.5) * this.lineH;
    let dx = gx - this.ox, dy = gy - this.oy;
    const len = Math.max(1, Math.hypot(dx, dy)); dx /= len; dy /= len;
    const speed = expTail(300, 500, 2400) * Math.max(0.7, this.R / 1500) / TEMPO;
    const tang = rand(-0.45, 0.45);
    this.parts.push({ x: gx, y: gy, vx: (dx - dy * tang) * speed, vy: (dy + dx * tang) * speed,
                      ch: this.pool.charCodeAt(Math.floor(Math.random() * this.pool.length)), decay: -1, settled: false });
  }
  /** True once every settled glyph has faded out. */
  finished() {
    if (this.tick / TICK_HZ < this.duration + 0.6) return false;
    if (this.parts.some(p => !p.settled)) return false;
    const last = this.tick - 5.2 * TICK_HZ;
    for (let i = 0; i < this.state.length; i++) if (this.state[i] === 3 && this.hit[i] > last) return false;
    return true;
  }
}

