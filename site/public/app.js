// ── boot ──
function boot() {
  const hero = D.querySelector('.hero');
  const h = hero ? Hero(hero) : null;
  D.querySelectorAll('[data-ignite-top]').forEach(b => b.addEventListener('click', () => {
    if (!h) return;
    window.scrollTo({ top: 0, behavior: RM ? 'auto' : 'smooth' });
    const t0 = performance.now();
    const wait = () => (window.scrollY < 4 || performance.now() - t0 > 1400) ? h.ignite() : requestAnimationFrame(wait);
    requestAnimationFrame(wait);
  }));
  D.querySelectorAll('[data-widgets]').forEach(Widgets);
  D.querySelectorAll('[data-transcript]').forEach(Transcript);
  D.querySelectorAll('[data-checklist]').forEach(Checklist);
  D.querySelectorAll('[data-media]').forEach(Media);
  D.querySelectorAll('[data-browsed]').forEach(Browsed);
  Reveals();
  D.querySelectorAll('[data-spin-404]').forEach(Spin404);
}

// ── 404: a turn that finds nothing ────────────────────────────────────────
function Spin404(el) {
  const g = el.querySelector('.sp__g'), v = el.querySelector('.sp__v'), p = el.querySelector('.sp__p');
  const t0 = performance.now();
  if (RM) { g.textContent = '✻'; v.textContent = 'Searched for 2s'; p.textContent = ' · nothing at this path'; el.classList.add('is-done'); return; }
  const tick = () => {
    const s = (performance.now() - t0) / 1000;
    if (s > 3.2) { g.textContent = '✻'; v.textContent = `Searched for ${timeString(s)}`; p.textContent = ' · nothing at this path'; el.classList.add('is-done'); return; }
    g.textContent = glyphAt(s);
    p.textContent = s > 1.2 ? ` (${timeString(s)} · ↓ ${Math.floor(s * 7)} files)` : '';
    requestAnimationFrame(tick);
  };
  tick();
}

