// Per-font measured widths, so fallback glyphs (✽ isn't in SF Mono) and CJK
// verbs land where they actually paint.
const widthCache = new Map();
function wOf(ctx, s) {
  const k = ctx.font + '\u0001' + s;
  let w = widthCache.get(k);
  if (w === undefined) { w = ctx.measureText(s).width; widthCache.set(k, w); }
  return w;
}
function setFont(ctx, px, weight = 400) {
  ctx.font = `${weight} ${px}px ${MONO}`;
  if (!ctx.font.includes('px')) ctx.font = `${weight} ${px}px Menlo, monospace`;
}

// ── The spinner: Claude Code's request lifecycle (updateSpinner et al.) ────
class Spinner {
  constructor() { this.verb = VERBS[0]; this.rateMean = 72; this.surge = 1.35; }
  start(now, fresh = true) {
    this.phase = 'working'; this.phaseStart = now;
    // The saver's turns are minutes long; a page visit isn't. Same shape, shorter tail.
    this.workDuration = expTail(18, 22, 80);
    this.doneDuration = rand(5, 8);
    if (fresh) this.verb = pickVerb(this.verb);
    this.tokens = 0; this.segEndsAt = -1; this.down = true; this.step = 'prefill';
    this.nextStatusRoll = now + rand(3, 7); this.statusShowing = false;
    this.parenDelay = rand(1.2, 4.0);
  }
  /** First impression: already deep into a turn, climbing the ladder, a few
      seconds from resting on "✻ Verbed for 1m 12s". */
  seed(now) {
    this.start(now, false);
    this.verb = VERBS.find(v => v[0] === 'Sprokbooking') || VERBS[0];
    this.phaseStart = now - 64; this.parenDelay = 2; this.workDuration = 72;
    this.tokens = 1180; this.step = 'decode'; this.down = true;
    this.segStart = now - 6; this.segEndsAt = now + 8.6; this.segRate = 64;
    this.statusShowing = true; this.statusEnteredAt = now - 11; this.statusShowUntil = now + 6.5;
    this.jit = 1;
  }
  streaming(now) { return this.phase === 'working' && now - this.phaseStart >= this.parenDelay; }
  speedTarget(now) {
    return !this.streaming(now) ? 0.22 : this.step === 'toolWait' ? 0.5 : this.down ? 1.0 : this.surge;
  }
  update(now, dt) {
    if (this.phase === 'done') { if (now - this.phaseStart >= this.doneDuration) this.start(now); return; }
    if (now - this.phaseStart >= this.parenDelay) {
      if (this.segEndsAt < 0) this.beginRequest(now);
      if (this.step === 'prefill') {
        const f = clamp((now - this.segStart) / (this.segEndsAt - this.segStart), 0, 1);
        this.tokens = this.preBase + this.preCount * f;
      } else if (this.step === 'decode') {
        this.jit = this.jit === undefined ? 1 : this.jit;
        this.jit += (1 - this.jit) * Math.min(1, dt / 1.2);
        this.jit = clamp(this.jit + gauss(0, 0.28 * Math.sqrt(dt)), 0.55, 1.6);
        const edge = Math.min(1.2, (this.segEndsAt - this.segStart) * 0.35);
        const ease = smooth01((now - this.segStart) / edge) * smooth01((this.segEndsAt - now) / edge);
        this.tokens += this.segRate * ease * this.jit * dt;
      }
      if (now >= this.segEndsAt) {
        if (this.step === 'prefill') this.beginStep('decode', now);
        else if (this.step === 'decode') {
          if (now - this.phaseStart >= this.workDuration) {
            this.doneText = `✻ ${this.verb[1]} for ${timeString(now - this.phaseStart)}`;
            this.phase = 'done'; this.phaseStart = now; return;
          }
          this.beginStep('toolWait', now);
        } else this.beginRequest(now);
      }
    }
    if (this.statusShowing) {
      if (this.step !== 'decode' || this.segEndsAt < 0 || now >= this.statusShowUntil) {
        this.statusShowing = false; this.nextStatusRoll = now + rand(3, 7);
      }
    } else if (this.step === 'decode' && this.segEndsAt > 0 && now >= this.nextStatusRoll) {
      const room = this.segEndsAt - now - 1;
      if (room >= 2) {
        this.statusEnteredAt = now;
        this.statusShowUntil = now + Math.min(expTail(6, 9, 90), room);
        this.statusShowing = true;
      } else this.nextStatusRoll = now + rand(3, 7);
    }
  }
  beginRequest(now) {
    this.rateMean = clamp(this.rateMean + gauss(0, 2.5) + (72 - this.rateMean) * 0.06, 45, 110);
    this.beginStep('prefill', now);
  }
  beginStep(next, now) {
    this.step = next; this.down = next === 'decode'; this.segStart = now;
    if (next === 'prefill') {
      this.preBase = this.tokens;
      this.preCount = Math.random() < 0.2 ? rand(2000, 9000) : expTail(100, 450, 2000);
      const dur = Math.max(1, gauss(3, 1));
      this.segEndsAt = now + dur;
      this.surge = 1.35 + 0.65 * smooth01(Math.log(this.preCount / dur / 100) / Math.log(50));
    } else if (next === 'decode') {
      this.segRate = Math.max(15, gauss(this.rateMean, this.rateMean * 0.1));
      this.segEndsAt = now + (Math.random() < 0.08 ? expTail(30, 150, Infinity) : expTail(5, 9, Infinity));
    } else {
      this.segEndsAt = now + (Math.random() < 0.05 ? rand(8, 30) : Math.max(0.3, gauss(2.5, 0.8)));
    }
  }
  status(now) {
    const s = now - this.statusEnteredAt;
    return s < 10 ? 'coding with xhigh effort' : s < 20 ? 'still coding with xhigh effort'
      : s < 30 ? 'coding more with xhigh effort' : s < 45 ? 'coding some more with xhigh effort'
      : 'almost done coding with xhigh effort';
  }
}

/* Builds the statusline as styled runs: [{t, c, a, bold, glow}] — glyph and
   glowing verb, then the dim parenthetical once the first chunk "arrives". */
function glyphAt(now) { return FRAMES[Math.round((1 - Math.cos(2 * Math.PI * now / 2)) / 2 * 5)]; }
function spinnerRuns(sp, now) {
  if (sp.phase === 'done') return { head: [{ t: sp.doneText, c: [1, 1, 1], a: 0.55 }], paren: [] };
  const head = [{ t: glyphAt(now) + ' ', glyph: true }];
  const verb = sp.verb[0] + '…';
  head.push({ t: verb, verb: true });
  const paren = [];
  if (now - sp.phaseStart >= sp.parenDelay) {
    const g = (t, a) => paren.push({ t, c: [1, 1, 1], a });
    g('(', 0.26); g(timeString(now - sp.phaseStart), 0.5); g(' · ', 0.26);
    g(`${sp.down ? '↓' : '↑'} ${countString(sp.tokens)} ${UNIT}`, 0.5);
    if (sp.statusShowing) { g(' · ', 0.26); g(sp.status(now), 0.42); }
    g(')', 0.26);
  }
  return { head, paren };
}

/* Draws runs at (x, y baseline). Verb chars get the left-to-right glow sweep. */
function drawRuns(ctx, runs, x, y, size, now, accent = C.accent, hot = C.accentHot, phase = 0) {
  for (const r of runs) {
    if (r.glyph) {
      setFont(ctx, size, 600);
      ctx.shadowColor = rgba(hot, 0.8); ctx.shadowBlur = size * 0.5;
      ctx.fillStyle = rgba(mix(accent, hot, 0.3));
      ctx.fillText(r.t, x, y); x += wOf(ctx, r.t);
      ctx.shadowBlur = 0;
    } else if (r.verb) {
      setFont(ctx, size, 600);
      const chars = Array.from(r.t);
      const period = chars.length + 16;
      const pos = (((now + phase) * 13) % period + period) % period - 5;
      chars.forEach((ch, i) => {
        const d = i - pos, b = Math.exp(-(d * d) / (2 * 1.9 * 1.9));
        ctx.fillStyle = rgba(mix(accent, C.glow, 0.9 * b));
        if (b > 0.1) { ctx.shadowColor = rgba(hot, 0.9 * b); ctx.shadowBlur = size * 0.65 * b; }
        ctx.fillText(ch, x, y); x += wOf(ctx, ch);
        ctx.shadowBlur = 0;
      });
    } else {
      setFont(ctx, size, 400);
      ctx.fillStyle = rgba(r.c, r.a);
      ctx.fillText(r.t, x, y); x += wOf(ctx, r.t);
    }
  }
  return x;
}
function runsWidth(ctx, runs, size) {
  let w = 0;
  for (const r of runs) {
    setFont(ctx, size, r.glyph || r.verb ? 600 : 400);
    if (r.verb) for (const ch of r.t) w += wOf(ctx, ch); else w += wOf(ctx, r.t);
  }
  return w;
}
function roundRect(ctx, x, y, w, h, r) {
  ctx.beginPath();
  if (ctx.roundRect) ctx.roundRect(x, y, w, h, r); else ctx.rect(x, y, w, h);
}

// ── The clock: 3×5 half-block digits in a heavy TUI box ───────────────────
const BLOCK = {
  0: ['111', '101', '101', '101', '111'], 1: ['010', '110', '010', '010', '111'],
  2: ['111', '001', '111', '100', '111'], 3: ['111', '001', '011', '001', '111'],
  4: ['101', '101', '111', '001', '001'], 5: ['111', '100', '111', '001', '111'],
  6: ['111', '100', '111', '101', '111'], 7: ['111', '001', '001', '010', '010'],
  8: ['111', '101', '111', '101', '111'], 9: ['111', '101', '111', '001', '111'],
  ':': ['0', '1', '0', '1', '0'],
};
const H12 = !/^(h23|h24)$/.test(new Intl.DateTimeFormat(undefined, { hour: 'numeric' }).resolvedOptions().hourCycle || 'h12');
const WD = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
const MO = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
function clockModel(d) {
  let h = d.getHours();
  const ampm = h >= 12 ? 'PM' : 'AM';
  if (H12) { h = h % 12 || 12; }
  const hs = H12 ? String(h) : String(h).padStart(2, '0');
  const time = `${hs}:${String(d.getMinutes()).padStart(2, '0')}:${String(d.getSeconds()).padStart(2, '0')}`;
  const date = `/* ${WD[d.getDay()]} ${MO[d.getMonth()]} ${d.getDate()} ${d.getFullYear()} */`;
  const grid = ['', '', '', '', ''], seg = [];
  let colons = 0;
  for (const ch of time) {
    const bits = BLOCK[ch];
    const s = ch === ':' ? (colons++, 'colon') : colons >= 2 ? 'sec' : 'digit';
    for (let r = 0; r < 5; r++) grid[r] += bits[r] + '0';
    for (let k = 0; k < bits[0].length; k++) seg.push(s);
    seg.push('gap');
  }
  for (let r = 0; r < 5; r++) grid[r] = grid[r].slice(0, -1);
  seg.pop();
  const suffix = H12 ? ' ' + ampm : '';
  const lead = suffix ? 1 : 0;
  const elementW = lead + seg.length + suffix.length;
  const inner = Math.max(elementW + 10, date.length + 4);
  return { date, grid, seg, suffix, inner, leftPad: Math.floor((inner - elementW) / 2) + lead,
           key: time + date };
}
const CLOCK_C = { digit: '#c7c7c7', colon: '#5f5f5f', sec: '#7d7d7d', border: '#4a4a4a', date: '#5c6670', ampm: '#707070' };

/* Renders the clock box into its own canvas (the saver caches a raster too;
   it only changes once a second). Returns {cv, w, h} in CSS px. */
function renderClock(cv, m, cf, dpr) {
  const ctx = cv.getContext('2d');
  setFont(ctx, cf, 400);
  const cw = wOf(ctx, '█');
  const step = cf * 1.06;
  const pad = cf * 1.2;
  const boxW = (m.inner + 2) * cw, boxH = 7 * step;
  const w = boxW + cw * 1.2 + pad * 2, h = boxH + step * 0.5 + pad * 2;
  cv.width = Math.ceil(w * dpr); cv.height = Math.ceil(h * dpr);
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
  ctx.clearRect(0, 0, w, h);
  roundRect(ctx, pad, pad, boxW + cw * 1.2, boxH + step * 0.5, 2);
  ctx.fillStyle = 'rgba(0,0,0,0.375)'; ctx.fill();
  const x0 = pad + cw * 0.6, y0 = pad + step * 0.25;
  setFont(ctx, cf, 400);
  ctx.textBaseline = 'middle';
  ctx.shadowColor = 'rgba(0,0,0,0.9)'; ctx.shadowBlur = cf * 0.6;
  const rowY = r => y0 + r * step + step / 2;
  // top rail: ┏━━ /* date */ ━━┓
  const fillN = Math.max(0, m.inner - m.date.length - 2), left = Math.floor(fillN / 2);
  let x = x0;
  const put = (s, c) => { ctx.fillStyle = c; ctx.fillText(s, x, rowY(0)); x += s.length * cw; };
  put('┏' + '━'.repeat(left) + ' ', CLOCK_C.border);
  put(m.date, CLOCK_C.date);
  put(' ' + '━'.repeat(fillN - left) + '┓', CLOCK_C.border);
  ctx.fillStyle = CLOCK_C.border;
  for (let r = 1; r <= 5; r++) { ctx.fillText('┃', x0, rowY(r)); ctx.fillText('┃', x0 + (m.inner + 1) * cw, rowY(r)); }
  ctx.fillText('┗' + '━'.repeat(m.inner) + '┛', x0, rowY(6));
  // digits: each bitmap pixel is a half-block cell, drawn as a seamless rect
  const gx = x0 + (1 + m.leftPad) * cw;
  // Each bitmap pixel is a half-block cell. Runs of one colour are merged and
  // snapped to device pixels, so cells tile without antialiased seams.
  const snap = v => Math.round(v * dpr) / dpr;
  for (const pass of [0, 1]) {   // the scrim under everything first, then crisp cells
    ctx.shadowBlur = pass ? 0 : cf * 0.6;
    for (let r = 0; r < 5; r++) {
      const ya = snap(y0 + 2 * step + r * step / 2), yb = snap(y0 + 2 * step + (r + 1) * step / 2);
      for (let i = 0; i < m.seg.length; i++) {
        if (m.grid[r][i] !== '1') continue;
        let j = i;
        while (j + 1 < m.seg.length && m.grid[r][j + 1] === '1' && m.seg[j + 1] === m.seg[i]) j++;
        const xa = snap(gx + i * cw), xb = snap(gx + (j + 1) * cw);
        ctx.fillStyle = CLOCK_C[m.seg[i]];
        ctx.fillRect(xa, ya, xb - xa, yb - ya);
        i = j;
      }
    }
  }
  if (m.suffix) { ctx.fillStyle = CLOCK_C.ampm; ctx.fillText(m.suffix, gx + m.seg.length * cw, rowY(4)); }
  ctx.shadowBlur = 0;
  return { w, h, pad, boxW, boxH };
}

